"""
statistical_tests.py
────────────────────
Statistical analysis of the results from `train_kfold.py`.

What it computes
----------------
1) 95% CI of the mean AUC per (model, muscle) with two methods:
     - Student's t over the 5 per-fold AUCs  (primary)
     - bootstrap (N=1000) over the 5 AUCs    (complementary, non-parametric)
   Note: bootstrap over concatenated predictions is NOT used because each
   fold comes from a different model with its own calibration, and mixing
   their probabilities degrades the global ranking.
2) Comparison vs. the clinical baseline of Martinez-Paya 2017:
   - If the published AUC falls OUTSIDE the t-Student 95% CI, we declare a
     "statistically significant difference" (p<0.05).
   - If it falls INSIDE, the result is "equivalent / inconclusive".
3) Clinical metrics recalibrated with Youden's J:
   - Search for the optimal per-fold threshold that maximises Sens+Spec-1.
   - Comparison against the fixed 0.5 threshold used by the model by default.
4) Paired comparison between architectures within the same muscle:
   - Wilcoxon signed-rank test over the 5 per-fold AUCs (paired).
   - DeLong test over concatenated predictions (real ROC).
   - McNemar test over binary hits/misses.

Input
-----
`models/resultados_kfold/kfold_predictions.json` (generated by train_kfold.py)

Output
------
- models/resultados_kfold/ci_bootstrap.csv           (CI95% per model/muscle)
- models/resultados_kfold/vs_baseline.csv            (comparison with Martinez-Paya)
- models/resultados_kfold/recalibrated_youden.csv    (Sens/Spec at optimal threshold)
- models/resultados_kfold/pairwise_models.csv        (tests between architectures)
- models/resultados_kfold/plots/boxplot_auc_{muscle}.png
- models/resultados_kfold/informe_estadistico.txt

Usage
-----
    cd src
    python3 statistical_tests.py
"""
